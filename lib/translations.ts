export function useTranslation() {
  const mounted = useMounted();
  const locale = useLanguageStore((s) => s.locale);
  const setLocale = useLanguageStore((s) => s.setLocale);
  const toggleLocale = useLanguageStore((s) => s.toggleLocale);

  // Fallback to 'en' during initial SSR mount to prevent hydration mismatch
  const activeLocale: Locale = mounted ? locale : "en";
  const t = translations[activeLocale];

  const pick = (enText: string, mrText?: string | null) => {
    if (activeLocale === "mr" && mrText) {
      return mrText;
    }
    return enText;
  };

  return {
    t,
    locale: activeLocale,
    setLocale,
    toggleLocale,
    pick,
  };
}

